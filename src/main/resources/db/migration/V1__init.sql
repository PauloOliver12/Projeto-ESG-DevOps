CREATE TABLE environmental_license (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR2(50 CHAR) NOT NULL,
    company_name VARCHAR2(150 CHAR) NOT NULL,
    license_type VARCHAR2(100 CHAR) NOT NULL,
    status VARCHAR2(30 CHAR) NOT NULL,
    issued_at DATE NOT NULL,
    expires_at DATE NOT NULL,
    responsible_email VARCHAR2(150 CHAR) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_environmental_license_code UNIQUE (code)
);

CREATE TABLE internal_audit (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environmental_license_id NUMBER NOT NULL,
    auditor_name VARCHAR2(120 CHAR) NOT NULL,
    scheduled_at TIMESTAMP NOT NULL,
    status VARCHAR2(30 CHAR) NOT NULL,
    findings VARCHAR2(2000 CHAR),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_license FOREIGN KEY (environmental_license_id)
        REFERENCES environmental_license (id)
);

CREATE TABLE compliance_alert (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environmental_license_id NUMBER NOT NULL,
    severity VARCHAR2(20 CHAR) NOT NULL,
    message VARCHAR2(500 CHAR) NOT NULL,
    resolved NUMBER(1) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_alert_license FOREIGN KEY (environmental_license_id)
        REFERENCES environmental_license (id)
);

CREATE INDEX idx_environmental_license_status ON environmental_license (status);
CREATE INDEX idx_environmental_license_expires_at ON environmental_license (expires_at);
CREATE INDEX idx_internal_audit_status ON internal_audit (status);
CREATE INDEX idx_compliance_alert_resolved ON compliance_alert (resolved);
